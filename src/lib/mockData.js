export const getProductById = (id) => {
  console.log("getProductById called with:", id, "Type:", typeof id);
  const productId = typeof id === "string" ? parseInt(id, 10) : id;
  console.log("Parsed productId:", productId);
  const found = mockProducts.find((product) => product.id === productId);
  console.log("Found product:", found ? found.name : "null");
  return found || null;
};

export const getRelatedProducts = (currentProductId, limit = 3) => {
  const productId =
    typeof currentProductId === "string"
      ? parseInt(currentProductId, 10)
      : currentProductId;
  const currentProduct = getProductById(productId);

  if (!currentProduct) {
    return mockProducts.slice(0, limit);
  }

  const relatedByCategory = mockProducts.filter(
    (product) =>
      product.id !== productId && product.category === currentProduct.category
  );

  if (relatedByCategory.length < limit) {
    const remaining = mockProducts.filter(
      (product) =>
        product.id !== productId &&
        !relatedByCategory.some((p) => p.id === product.id)
    );
    return [...relatedByCategory, ...remaining].slice(0, limit);
  }

  return relatedByCategory.slice(0, limit);
};

export const getAllProducts = (filters = {}) => {
  let filtered = [...mockProducts];

  if (filters.category && filters.category !== "All") {
    filtered = filtered.filter((p) => p.category === filters.category);
  }

  if (filters.minPrice) {
    filtered = filtered.filter((p) => p.price >= filters.minPrice);
  }

  if (filters.maxPrice) {
    filtered = filtered.filter((p) => p.price <= filters.maxPrice);
  }

  if (filters.search) {
    const searchLower = filters.search.toLowerCase();
    filtered = filtered.filter((p) =>
      p.name.toLowerCase().includes(searchLower)
    );
  }

  return filtered;
};

